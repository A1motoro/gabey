"""exp00 — CV baseline on the CA slice (owner: A, M1 data side only).

Purpose: make the "what does CV already achieve?" number reproducible **before** CA
exists. This script does not implement or modify any predictor — it imports P's
``ConstantVelocityPredictor`` unchanged and scores it on the fixed slices that M1 owns
(``ca_scenario_set()`` + ``prediction_slices()``), so every predictor later gets exactly
the same 12 x 25 problems.

Why the CA slice and not ``load_toy()``: the course clip is 12.9 s of near-constant speed
with no lane change, so an acceleration model cannot be distinguished from CV there.
On ``a_cutter = ±2`` cut-ins the cutter ramps its longitudinal speed during the merge, and
CV's ADE roughly doubles — that gap is the room left for CA (see docs/CA_scenario_support.md).

Outputs (regenerated by running this file):
    outputs/logs/exp00_cv_ade.csv     one row per (scenario, slice): ADE / FDE
    outputs/figures/exp00_cv_ade.png  ADE vs t0 per a_cutter + per-phase means

Run:  python experiments/exp00_cv_ade.py
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))  # runnable without `pip install -e .`

from pbs.data import ca_scenario_set, prediction_slices  # noqa: E402
from pbs.eval.metrics import ade, fde  # noqa: E402
from pbs.prediction import ConstantVelocityPredictor  # noqa: E402

FIG_DIR = ROOT / "outputs" / "figures"
LOG_DIR = ROOT / "outputs" / "logs"

HISTORY = 1.0  # s, sliding window handed to the predictor
HORIZON = 2.0  # s, forecast length
STRIDE = 0.5  # s between consecutive t0
PHASES = ("before ramp", "in ramp", "after ramp")


def _phase(scenario, t0: float) -> str:
    """Which part of the cutter's acceleration ramp the slice starts in."""
    t_start = float(scenario.params["cut_in_t"])
    t_end = t_start + float(scenario.params["accel_T"])
    if t0 < t_start - 1e-9:
        return PHASES[0]
    if t0 <= t_end + 1e-9:
        return PHASES[1]
    return PHASES[2]


def collect() -> list[dict]:
    """One record per (scenario, slice) for the unchanged CV predictor."""
    predictor = ConstantVelocityPredictor()
    rows: list[dict] = []
    for sc in ca_scenario_set().scenarios:
        for sl in prediction_slices(sc, history=HISTORY, horizon=HORIZON, stride=STRIDE):
            pred = predictor.predict(sl.history, horizon=len(sl.truth), dt=sc.dt)
            rows.append(
                {
                    "kind": sc.kind,
                    "a_cutter": float(sc.params["a_cutter"]),
                    "gap_d": float(sc.params["gap_d"]),
                    "rel_v": float(sc.params["rel_v"]),
                    "t0": float(sl.t0),
                    "phase": _phase(sc, sl.t0),
                    "ade_m": ade(pred, sl.truth),
                    "fde_m": fde(pred, sl.truth),
                    "history_points": int(len(sl.history.t)),
                }
            )
    return rows


def _mean(values) -> float:
    values = list(values)
    return float(np.mean(values)) if values else float("nan")


def write_csv(rows: list[dict]) -> Path:
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    path = LOG_DIR / "exp00_cv_ade.csv"
    columns = ("a_cutter", "gap_d", "rel_v", "t0", "phase", "ade_m", "fde_m", "history_points")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        for row in sorted(rows, key=lambda r: (r["a_cutter"], r["gap_d"], r["rel_v"], r["t0"])):
            writer.writerow({k: (f"{row[k]:.4f}" if k.endswith("_m") else row[k]) for k in columns})
    return path


def plot(rows: list[dict]) -> Path:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig, (ax_t, ax_p) = plt.subplots(1, 2, figsize=(11.0, 4.2), dpi=150)

    accels = sorted({r["a_cutter"] for r in rows})
    colors = {accels[0]: "#1f77b4", 0.0: "#2ca02c", accels[-1]: "#d62728"}
    styles = {accels[0]: "--", 0.0: "-", accels[-1]: "-"}
    for a in accels:
        subset = [r for r in rows if r["a_cutter"] == a]
        t0s = sorted({r["t0"] for r in subset})
        means = [_mean(r["ade_m"] for r in subset if r["t0"] == t0) for t0 in t0s]
        ax_t.plot(t0s, means, styles[a], marker="o", markersize=3, color=colors[a],
                  label=f"a_cutter = {a:+g}")
    ax_t.axvspan(0.5, 3.5, color="0.85", alpha=0.6, zorder=0)
    ax_t.text(2.0, ax_t.get_ylim()[1] * 0.92, "acceleration ramp", ha="center", fontsize=8)
    ax_t.set_xlabel("slice start t0 [s]")
    ax_t.set_ylabel("CV ADE [m]")
    ax_t.set_title("CV error over the 12 CA scenarios (mean over gap_d / rel_v)")
    ax_t.grid(alpha=0.3)
    ax_t.legend(fontsize=8)

    width = 0.8 / len(accels)
    present = [p for p in PHASES if any(r["phase"] == p for r in rows)]
    indices = np.arange(len(present))
    for k, a in enumerate(accels):
        means = [_mean(r["ade_m"] for r in rows if r["a_cutter"] == a and r["phase"] == phase)
                 for phase in present]
        ax_p.bar(indices + k * width, means, width, color=colors[a], label=f"{a:+g}")
    ax_p.set_xticks(indices + width * (len(accels) - 1) / 2, present)
    ax_p.set_ylabel("CV ADE [m]")
    ax_p.set_title("CV ADE by acceleration phase")
    ax_p.annotate("0 (CV is exact)", xy=(indices[-1], 0.0), xytext=(indices[-1], 0.25),
                  fontsize=8, ha="center")
    ax_p.grid(alpha=0.3, axis="y")
    ax_p.legend(fontsize=8, title="a_cutter")

    fig.suptitle("exp00 — CV baseline on ca_scenario_set() slices (history=1.0 s, horizon=2.0 s)")
    fig.tight_layout()
    path = FIG_DIR / "exp00_cv_ade.png"
    fig.savefig(path)
    plt.close(fig)
    return path


def summarize(rows: list[dict]) -> None:
    scenarios = {(r["a_cutter"], r["gap_d"], r["rel_v"]) for r in rows}
    print(f"scenarios         : {len(scenarios)}")
    print(f"slices            : {len(rows)} total, {len(rows) // len(scenarios)} per scenario")
    points = sorted({r["history_points"] for r in rows})
    print(f"history points    : {points} (sliding {HISTORY:g} s window)")
    print()
    print(f"{'a_cutter':>9} {'n':>4} {'ADE mean':>9} {'FDE mean':>9}   meaning")
    for a in sorted({r["a_cutter"] for r in rows}):
        subset = [r for r in rows if r["a_cutter"] == a]
        note = "constant speed -> CV is exact" if a == 0 else "speed ramp -> CV lags"
        print(f"{a:>+9g} {len(subset):>4} {_mean(r['ade_m'] for r in subset):>9.3f} "
              f"{_mean(r['fde_m'] for r in subset):>9.3f}   {note}")
    print()

    present = [p for p in PHASES if any(r["phase"] == p for r in rows)]
    print(f"{'a_cutter':>9} " + " ".join(f"{phase:>12}" for phase in present))
    for a in sorted({r["a_cutter"] for r in rows}):
        cells = []
        for phase in present:
            value = _mean(r["ade_m"] for r in rows if r["a_cutter"] == a and r["phase"] == phase)
            cells.append(f"{value:>12.3f}")
        print(f"{a:>+9g} " + " ".join(cells))
    missing = [p for p in PHASES if p not in present]
    if missing:
        print(
            f"\nnote: no slice starts in {', '.join(missing)} — cut_in_t = 0.5 s and the first"
            f" t0 = {HISTORY:g} s, so the ramp is already underway."
        )
    print("\nafter the ramp x and y are both linear, so CV is exact there (ADE 0) —"
          " CA can only lose on those slices.")
    print("This is the CV half of the exp01 comparison; CA (P) plugs into the same slices.")


def main() -> None:
    rows = collect()
    csv_path = write_csv(rows)
    fig_path = plot(rows)
    summarize(rows)
    print()
    print(f"wrote {csv_path.relative_to(ROOT)}")
    print(f"wrote {fig_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
