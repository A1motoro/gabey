def never_brake_log(scenario):
    """Ego keeps its speed for the whole horizon (the no-AEB reference)."""
    return run_sim(
        scenario, NullAssessor(), NeverBrakePolicy(), duration=scenario.params["duration"]
    )


def distance_series(scenario, log) -> np.ndarray:
    """Ego ↔ first agent centre distance at every simulation step [m]."""
    agent = scenario.agents[0]
    ax = np.interp(log.t, agent.t, agent.x)
    ay = np.interp(log.t, agent.t, agent.y)
    return np.hypot(log.ego_x - ax, log.ego_y - ay)


def analytic_contact_time(scenario) -> float:
    """Closed-form contact time where one exists, else ``nan``.

    cut_in: the cutter were already centred in the ego lane, so a purely longitudinal
    closing problem; contact at ``(gap_d − r_safe)/rel_v``. It is a *lower bound* on the
    simulated contact time, because the cutter is still laterally displaced while it
    merges — the gap between the two is exactly why the danger map is not a straight line.
    crossing: |arrival_t − gap_d/v_ego| = how far apart in time the two arrivals are.
    """
    params = scenario.params
    if scenario.kind == "cut_in":
        rel_v = params["rel_v"]
        return max(0.0, (params["gap_d"] - R_SAFE) / rel_v) if rel_v > 0 else float("nan")
    if scenario.kind == "crossing":
        return abs(params["arrival_t"] - params["gap_d"] / params["v_ego"])
    return float("nan")


def audit(scenario) -> dict:
    """One table row: is it benign, and how close does the no-braking ego get?"""
    log = never_brake_log(scenario)
    dist = distance_series(scenario, log)
    k = int(np.argmin(dist))
    row = {
        "kind": scenario.kind,
        "label": scenario_label(scenario),
        "v_ego": scenario.params.get("v_ego", float("nan")),
        "benign": not log.collision,
        "collision": bool(log.collision),
        "min_dist": float(dist[k]),
        "t_min_dist": float(log.t[k]),
        "t_contact_analytic": analytic_contact_time(scenario),
    }
    for key in CSV_COLUMNS:
        if key not in row and key in scenario.params:
            row[key] = scenario.params[key]
    return row


def rejection_sensitivity() -> list[dict]:
    """How many lane-change durations pass the plausibility filter, per comfort bound."""
    lc_t_values = [1.5, 2.0, 2.5, 3.0, 4.0, 5.0]
    rows = []
    for bound in (2.0, 3.0, 4.5):
        accepted = []
        for lc_T in lc_t_values:
            built = scenario_set(
                kinds=("cut_in",),
                grid={"cut_in": {"gap_d": [25.0], "rel_v": [2.0], "lc_T": [lc_T]}},
                max_lat_acc=bound,
                strict=False,
            )
            if built.n_built:
                accepted.append(lc_T)
        rows.append(
            {
                "max_lat_acc": bound,
                "accepted_lc_T": accepted,
                "n_accepted": len(accepted),
                "n_tested": len(lc_t_values),
                "min_lc_T": min_lc_duration(LANE_WIDTH, bound),
            }
        )
    return rows


