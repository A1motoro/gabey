"""exp00 — M1 scenario baseline check (owner: A).

This is the **scenario baseline**: it validates the parametric scenario family and defines
the *no-braking reference* on it, without using any prediction or risk code (M1 sits below
M2/M3 in the data flow). For every scenario it answers one question:

    if the ego never brakes, does it collide within the scenario horizon?

``no``  → the scenario is **benign**; any brake in it is a counterfactual false brake
          (spec §1.5), so the trade-off curve of exp02/exp03 has a denominator.
``yes`` → the scenario is **dangerous**; it is where an AEB can earn something.

Outputs (all regenerated by running this file):
    outputs/figures/exp00_scenario_geometry.png   one cut_in / lead_brake / crossing
    outputs/figures/exp00_lateral_accel.png       quintic profile + plausibility filter
    outputs/figures/exp00_danger_map.png          danger map per family
    outputs/logs/exp00_scenarios.csv              one row per scenario
    outputs/logs/exp00_summary.md                 counts, rejection stats, formulas

Run:  python experiments/exp00_scenarios.py
"""

