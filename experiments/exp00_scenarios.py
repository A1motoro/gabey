def _lane_band(ax) -> None:
    """Draw ego-lane centre, lane edges and adjacent-lane centres on a y-axis."""
    ax.axhline(0.0, color="0.35", lw=1.0, ls="--")
    for edge in (LANE_WIDTH / 2, -LANE_WIDTH / 2):
        ax.axhline(edge, color="0.75", lw=0.8, ls=":")
    for centre in (LANE_WIDTH, -LANE_WIDTH):
        ax.axhline(centre, color="0.75", lw=0.8, ls="-.")


def plot_geometry(cases: dict, path: Path) -> None:
    """Three panes: what each conflict type looks like in (x, y) or (t, x)."""
    fig, axes = plt.subplots(1, 3, figsize=(15.0, 4.6))

    # (a) cut_in -------------------------------------------------------------------
    ax = axes[0]
    sc = cases["cut_in_danger"]
    log = never_brake_log(sc)
    agent = sc.agents[0]
    _lane_band(ax)
    sca = ax.scatter(agent.x, agent.y, c=agent.t, cmap="viridis", s=9, zorder=3,
                     label="cutter")
    ax.plot([agent.x[0]], [agent.y[0]], "o", ms=9, mfc="none", mec="k", zorder=5,
            label="cutter at t = 0")
    ax.plot(log.ego_x, log.ego_y, color="tab:blue", lw=2.5, zorder=4,
            label="ego (never brakes)")
    fig.colorbar(sca, ax=ax, pad=0.01, label="t [s]")
    ax.annotate("ego lane", xy=(3.0, 0.28), fontsize=8, color="0.35")
    ax.annotate("adjacent lane centre", xy=(3.0, LANE_WIDTH + 0.25), fontsize=8, color="0.5")
    dist = distance_series(sc, log)
    if log.collision:
        k = int(np.argmax(dist < R_SAFE))
        ax.plot(log.ego_x[k], log.ego_y[k], "r*", ms=16, zorder=6,
                label=f"contact t={log.t[k]:.2f}s, d={dist[k]:.2f}m")
    ax.set_xlim(0.0, float(log.ego_x[-1]) * 0.62)
    ax.set_ylim(-4.4, 5.2)
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    ax.set_title("cut_in — lateral conflict\n" + scenario_label(sc), fontsize=10)
    ax.legend(loc="upper right", fontsize=7)

    # (b) lead_brake ---------------------------------------------------------------
    ax = axes[1]
    sc = cases["lead_brake_danger"]
    log = never_brake_log(sc)
    agent = sc.agents[0]
    ax.plot(log.t, log.ego_x, color="tab:blue", lw=2.0, label="ego (never brakes)")
    ax.plot(agent.t, agent.x, color="tab:orange", lw=2.0, label="lead")
    dist = distance_series(sc, log)
    if log.collision:
        k = int(np.argmax(dist < R_SAFE))
        ax.plot(log.t[k], log.ego_x[k], "r*", ms=16, label=f"contact t={log.t[k]:.2f}s")
    ax.set_xlabel("t [s]")
    ax.set_ylabel("x [m]")
    ax.set_title("lead_brake — longitudinal conflict\n" + scenario_label(sc), fontsize=10)
    ax.legend(loc="upper left", fontsize=8)

    # (c) crossing -----------------------------------------------------------------
    ax = axes[2]
    sc = cases["crossing_danger"]
    log = never_brake_log(sc)
    agent = sc.agents[0]
    _lane_band(ax)
    ax.plot(log.ego_x, log.ego_y, color="tab:blue", lw=2.0, label="ego (never brakes)")
    sca = ax.scatter(agent.x, agent.y, c=agent.t, cmap="viridis", s=12, zorder=3,
                     label="crossing agent")
    fig.colorbar(sca, ax=ax, pad=0.01, label="t [s]")
    dist = distance_series(sc, log)
    if log.collision:
        k = int(np.argmax(dist < R_SAFE))
        ax.plot(log.ego_x[k], log.ego_y[k], "r*", ms=16, label=f"contact t={log.t[k]:.2f}s")
    ax.set_xlim(0.0, 60.0)
    ax.set_ylim(-4.4, 10.0)
    ax.set_xlabel("x [m]")
    ax.set_ylabel("y [m]")
    ax.set_title("crossing — lateral conflict\n" + scenario_label(sc), fontsize=10)
    ax.legend(loc="lower right", fontsize=8)

    fig.suptitle("exp00 · the three scenario families (dangerous member of each)", fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def plot_lateral_accel(path: Path) -> None:
    """What the quintic actually does, and where the plausibility filter bites."""
    fig, axes = plt.subplots(1, 2, figsize=(12.0, 4.4))

    # (a) normalised profiles for one 3 s lane change
    ax = axes[0]
    T, dy = 3.0, LANE_WIDTH
    tau = np.linspace(0.0, 1.0, 401)
    t = tau * T
    ax.plot(tau, quintic_lateral(0.0, dy, T, t) / dy, label="y / Δy")
    ax.plot(tau, quintic_lateral_vel(0.0, dy, T, t) * T / dy, label="(dy/dt)·T / Δy")
    ax.plot(tau, quintic_lateral_acc(0.0, dy, T, t) * T**2 / dy,
            label="(d²y/dt²)·T² / Δy")
    tau_peak = (1.0 - 1.0 / np.sqrt(3.0)) / 2.0
    ax.axvline(tau_peak, color="0.6", lw=0.8, ls=":")
    ax.annotate(
        f"peak {10 / np.sqrt(3):.2f}\n@ τ={tau_peak:.3f}",
        xy=(tau_peak, 10 / np.sqrt(3)),
        xytext=(tau_peak + 0.06, 5.2),
        fontsize=8,
        arrowprops=dict(arrowstyle="->", lw=0.7),
    )
    ax.set_xlabel("τ = (t − t₀)/T")
    ax.set_ylabel("dimensionless")
    ax.set_title(f"quintic (minimum-jerk) lane change, Δy={dy:g} m, T={T:g} s", fontsize=10)
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3)

    # (b) peak lateral acceleration vs lane-change duration
    ax = axes[1]
    T_all = np.linspace(1.2, 6.0, 200)
    peak = np.array([peak_lateral_acc(dy, T) for T in T_all])
    ax.plot(T_all, peak, color="tab:blue", lw=2.0, label="peak |a_lat|")
    for bound, style in ((2.0, ":"), (MAX_LAT_ACC, "--"), (4.5, ":")):
        ax.axhline(bound, color="tab:red", lw=1.2, ls=style)
        ax.annotate(f"{bound:g} m/s²", xy=(5.4, bound), fontsize=8, color="tab:red",
                    va="bottom")
    ax.fill_between(T_all, peak, MAX_LAT_ACC, where=peak > MAX_LAT_ACC,
                    color="tab:red", alpha=0.12, label="rejected at 3 m/s²")
    t_min = min_lc_duration(dy, MAX_LAT_ACC)
    ax.axvline(t_min, color="0.4", lw=0.9, ls="-.")
    ax.annotate(f"min T = {t_min:.2f} s", xy=(t_min + 0.05, 1.0), fontsize=8, rotation=90)
    ax.set_xlabel("lane-change duration T [s]")
    ax.set_ylabel("peak lateral acceleration [m/s²]")
    ax.set_title(
        f"plausibility filter: |Δy|={dy:g} m, bound={MAX_LAT_ACC:g} m/s²\n"
        "dotted lines = sensitivity bounds 2.0 / 4.5 m/s²",
        fontsize=10,
    )
    ax.set_ylim(0, 8)
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(alpha=0.3)

    fig.suptitle("exp00 · quintic lateral profile and the physical-plausibility filter",
                 fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def plot_danger_map(built, path: Path) -> None:
    """Where does 'never braking' collide? One marker per grid point, per family."""
    fig, axes = plt.subplots(1, 3, figsize=(15.0, 4.6))

    # (a) cut_in: (gap_d, rel_v)
    ax = axes[0]
    for scenario, benign in built["cut_in"]:
        ax.scatter(scenario.params["gap_d"], scenario.params["rel_v"],
                   **marker_kwargs(benign))
    duration = built["cut_in"][0][0].params["duration"]
    rel = np.linspace(0.2, 6.5, 20)
    ax.plot(R_SAFE + rel * duration, rel, color="0.45", lw=1.0, ls="--",
            label="contact exactly at horizon\n(centred cutter)")
    ax.set_xlabel("gap_d at t=0 [m]")
    ax.set_ylabel("rel_v = ego − cutter [m/s]")
    ax.set_title("cut_in · danger map\n(markers = default grid)", fontsize=10)

    # (b) lead_brake: (init_gap, decel)
    ax = axes[1]
    for scenario, benign in built["lead_brake"]:
        ax.scatter(scenario.params["init_gap"], scenario.params["decel"],
                   **marker_kwargs(benign))
    ax.set_xlabel("init_gap at t=0 [m]")
    ax.set_ylabel("decel of lead [m/s²]")
    ax.set_title("lead_brake · danger map\n(benign only for far + gentle)", fontsize=10)

    # (c) crossing: (gap_d, arrival_t)
    ax = axes[2]
    for scenario, benign in built["crossing"]:
        ax.scatter(scenario.params["gap_d"], scenario.params["arrival_t"],
                   **marker_kwargs(benign))
    v_ego = built["crossing"][0][0].params["v_ego"]
    gaps = np.linspace(10.0, 55.0, 20)
    ax.plot(gaps, gaps / v_ego, color="0.45", lw=1.0, ls="--",
            label="simultaneous arrival")
    ax.set_xlabel("crossing point gap_d [m]")
    ax.set_ylabel("arrival_t [s]")
    ax.set_title("crossing · danger map\n(dangerous near the simultaneous-arrival line)",
                 fontsize=10)

    handles = [
        plt.Line2D([], [], ls="", marker="x", color="tab:red", label=DANGER["label"]),
        plt.Line2D([], [], ls="", marker="o", color="tab:green", markerfacecolor="none",
                   label=BENIGN["label"]),
    ]
    axes[0].legend(handles=handles, loc="lower right", fontsize=8)
    for ax in axes:
        ax.grid(alpha=0.3)
    fig.suptitle("exp00 · the no-braking baseline (M1 must contain both classes)",
                 fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


